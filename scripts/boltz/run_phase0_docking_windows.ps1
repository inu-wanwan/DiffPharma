param(
    [string]$BenchmarkRoot = "C:\Users\rixyt\workspace_eagle\sekijima_lab_local\DiffPharma\outputs\phase0_docking_windows",
    [string]$VinaRoot = "C:\Users\rixyt\workspace_eagle\sekijima_lab_local\DiffPharma\outputs\vina_gpu_2_official\Vina-GPU+"
)
$ErrorActionPreference = "Stop"
$prepared = Get-Content -Raw (Join-Path $BenchmarkRoot "prepared_inputs.json") | ConvertFrom-Json
$measurements = @()
Push-Location $VinaRoot
try {
    for ($index = 0; $index -lt $prepared.Count; $index++) {
        $item = $prepared[$index]
        $sampleRoot = Join-Path $BenchmarkRoot $item.label
        # Kernel1_Opt.bin and Kernel2_Opt.bin must first be generated by the
        # matching Vina-GPU+_K.exe.  The measured path then reuses those cached
        # kernels, matching the repeated-evaluation path in docking_GPU.py.
        $binary = "Vina-GPU+.exe"
        $arguments = @(
            "--receptor", (Join-Path $sampleRoot "receptor.pdbqt"),
            "--ligand_directory", (Join-Path $sampleRoot "ligands"),
            "--output_directory", (Join-Path $sampleRoot "output"),
            "--center_x", $item.center[0], "--center_y", $item.center[1], "--center_z", $item.center[2],
            "--size_x", "20", "--size_y", "20", "--size_z", "20", "--thread", "8000", "--search_depth", "16",
            "--seed", "0"
        )
        $timer = [System.Diagnostics.Stopwatch]::StartNew()
        $ErrorActionPreference = "Continue"
        & (Join-Path $VinaRoot $binary) @arguments 1> (Join-Path $sampleRoot "stdout.log") 2> (Join-Path $sampleRoot "stderr.log")
        $returnCode = $LASTEXITCODE
        $ErrorActionPreference = "Stop"
        $timer.Stop()
        $outputFile = Join-Path (Join-Path $sampleRoot "output") "ligand_out.pdbqt"
        $outputExists = Test-Path -LiteralPath $outputFile
        $measurements += [ordered]@{label=$item.label; elapsed_seconds=$timer.Elapsed.TotalSeconds; returncode=$returnCode; kernel_compile=$false; output_exists=$outputExists}
        $measurements | ConvertTo-Json | Set-Content -Encoding utf8 (Join-Path $BenchmarkRoot "timings.json")
        if ($returnCode -ne 0) { throw "$binary failed for $($item.label) with exit $returnCode" }
        if (-not $outputExists) { throw "$binary did not create $outputFile" }
    }
} finally {
    Pop-Location
}
